type ProviderBrandMarkProps = {
  brand: ProviderBrandId;
  label: string;
  className?: string;
};

export function ProviderBrandMark({ brand, label, className }: ProviderBrandMarkProps) {
  const [imageFailed, setImageFailed] = useState(false);
  const definition = BRAND_DEFINITIONS[brand];
  const shouldShowImage = definition.imageUrl && !imageFailed;

  return (
    <span
      className={cn(
        "flex size-10 shrink-0 items-center justify-center overflow-hidden rounded-2xl border border-black/5 shadow-sm",
        className,
      )}
      style={{ background: definition.background, color: definition.foreground }}
      title={label}
      aria-hidden="true"
    >
      {shouldShowImage ? (
        <img
          src={definition.imageUrl}
          alt=""
          className={cn("size-6 object-contain", definition.imageClassName)}
          loading="lazy"
          referrerPolicy="no-referrer"
          onError={() => setImageFailed(true)}
        />
      ) : definition.path ? (
        <svg viewBox="0 0 24 24" className="size-5" fill="currentColor" focusable="false">
          <path d={definition.path} />
        </svg>
      ) : (
        <span className="text-[11px] font-semibold leading-none tracking-tight">
          {definition.textFallback}
        </span>
      )}
    </span>
  );
}
